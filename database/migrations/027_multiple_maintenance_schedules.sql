-- Allow admins to maintain multiple independently managed windows.

CREATE TABLE IF NOT EXISTS public.store_maintenance_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode TEXT NOT NULL CHECK (mode IN ('scheduled', 'daily')),
    starts_at TIMESTAMPTZ,
    daily_time TIME WITHOUT TIME ZONE,
    duration_minutes INTEGER,
    message TEXT NOT NULL CHECK (length(btrim(message)) BETWEEN 1 AND 1000),
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT store_maintenance_schedule_mode_fields CHECK (
        (mode = 'scheduled' AND starts_at IS NOT NULL AND daily_time IS NULL)
        OR
        (mode = 'daily' AND starts_at IS NULL AND daily_time IS NOT NULL)
    ),
    CONSTRAINT store_maintenance_schedule_duration CHECK (
        duration_minutes IS NULL
        OR (
            duration_minutes BETWEEN 1 AND 43200
            AND (mode <> 'daily' OR duration_minutes < 1440)
        )
    ),
    CONSTRAINT store_maintenance_daily_duration_required CHECK (
        mode <> 'daily' OR duration_minutes IS NOT NULL
    )
);

ALTER TABLE public.store_maintenance_schedules ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.store_maintenance_schedules
    FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE
    ON TABLE public.store_maintenance_schedules
    TO service_role;
GRANT USAGE, SELECT
    ON SEQUENCE public.store_maintenance_schedules_id_seq
    TO service_role;

-- Preserve an existing single maintenance schedule when upgrading.
INSERT INTO public.store_maintenance_schedules (
    mode,
    starts_at,
    daily_time,
    duration_minutes,
    message,
    is_enabled
)
SELECT
    CASE
        WHEN maintenance_mode = 'daily' THEN 'daily'
        ELSE 'scheduled'
    END,
    CASE
        WHEN maintenance_mode IN ('now', 'scheduled')
            THEN COALESCE(maintenance_starts_at, NOW())
        ELSE NULL
    END,
    CASE
        WHEN maintenance_mode = 'daily' THEN maintenance_daily_time
        ELSE NULL
    END,
    maintenance_duration_minutes,
    COALESCE(NULLIF(btrim(maintenance_message), ''), 'Shop is closed now.'),
    TRUE
FROM public.store_settings
WHERE id = 1
  AND maintenance_mode <> 'off'
  AND (
      (maintenance_mode IN ('now', 'scheduled')
          AND (maintenance_starts_at IS NOT NULL OR maintenance_mode = 'now'))
      OR
      (maintenance_mode = 'daily'
          AND maintenance_daily_time IS NOT NULL
          AND maintenance_duration_minutes IS NOT NULL)
  )
  AND NOT EXISTS (
      SELECT 1
      FROM public.store_maintenance_schedules
  );
